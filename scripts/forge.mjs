import { appNetwork } from "../config/network.mjs"
import { spawnSync } from "node:child_process"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"

// ~/.local/bin/forge on some machines is an unrelated tool, so prefer Foundry's own install.
const forge =
  process.env.FOUNDRY_FORGE ?? `${process.env.HOME}/.foundry/bin/forge`
const command = process.argv[2] ?? "build"
const args = ["--root", "contracts"]
if (command === "test")
  args.push("--fork-url", process.env.MONAD_RPC_URL ?? appNetwork.rpc)
const result = spawnSync(forge, [command, ...args, ...process.argv.slice(3)], {
  stdio: "inherit",
  env: {
    ...process.env,
    PIPPO_USDC: appNetwork.payouts[0].usdc,
    PIPPO_TOKEN_MESSENGER: appNetwork.tokenMessenger,
  },
})
if (result.status !== 0) process.exit(result.status ?? 1)

if (command === "build") {
  const artifact = (name) =>
    JSON.parse(
      readFileSync(`contracts/out/ChequeBook.sol/${name}.json`, "utf8")
    )
  mkdirSync("lib", { recursive: true })
  writeFileSync(
    "lib/abi.ts",
    `// Generated by pnpm contracts:build.\nexport const chequeBookAbi = ${JSON.stringify(artifact("ChequeBook").abi)} as const\nexport const factoryAbi = ${JSON.stringify(artifact("ChequeBookFactory").abi)} as const\n`
  )
}
